import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { loadFlyModel } from "../../../../packages/game-renderer/src/fly-model.ts";

// Resolve the renderer's installed Three version, including its patched skinning implementation.
const renderer = fileURLToPath(new URL("../../../../packages/game-renderer/src/fly-model.ts", import.meta.url));
const { Box3, Vector3, Matrix4, Quaternion, SkinnedMesh, REVISION } = await import(import.meta.resolve("three", renderer));
const assetPath = new URL("../../../../assets/fly/fly.glb", import.meta.url);
const profilePath = new URL("../01/reference-profile.json", import.meta.url);
const outputPath = new URL("../../../../packages/game-renderer/src/retina-eye-rig.ts", import.meta.url);
const sha256 = bytes => createHash("sha256").update(bytes).digest("hex");
const [asset, profileBytes] = await Promise.all([readFile(assetPath), readFile(profilePath)]);
const profile = JSON.parse(profileBytes);
const model = await loadFlyModel(asset.buffer.slice(asset.byteOffset, asset.byteOffset + asset.byteLength));
const boundsByMesh = {};
let rig;
try {
  model.root.updateMatrixWorld(true);
  model.root.traverse(node => { if (node instanceof SkinnedMesh) node.skeleton.update(); });
  const eyes = ["L", "R"].map(side => {
    // Asset names are viewer-relative; physical L follows source +Y -> body +X.
    const sourceMesh = side === "L" ? "EyeR021" : "EyeL021";
    const eye = model.root.getObjectByName(sourceMesh);
    assert(eye instanceof SkinnedMesh, `${sourceMesh} must be the authored skinned eye`);
    const bounds = new Box3().setFromObject(eye, true);
    const center = bounds.getCenter(new Vector3());
    assert(side === "L" ? center.x > 0 : center.x < 0, "Anatomical eye handedness changed");
    boundsByMesh[sourceMesh] = { min: bounds.min.toArray(), max: bounds.max.toArray() };
    const matrix = profile.cameras.eyes[side].camera_to_native_body_rotation;
    const orientation = new Matrix4().set(...matrix[0], 0, ...matrix[1], 0, ...matrix[2], 0, 0, 0, 0, 1);
    const cameraToBodyQuaternion = new Quaternion().setFromRotationMatrix(orientation).normalize();
    const forward = new Vector3(0, 0, -1).applyQuaternion(cameraToBodyQuaternion);
    const up = new Vector3(0, 1, 0).applyQuaternion(cameraToBodyQuaternion);
    assert(side === "L" ? forward.x > 0 : forward.x < 0, "Optical lateral direction changed");
    assert(forward.z > 0 && up.y > .99, "Optical forward/up direction changed");
    return { side, sourceMesh, positionMetres: center.toArray(), cameraToBodyQuaternion: cameraToBodyQuaternion.toArray() };
  });
  rig = { assetSha256: sha256(asset), referenceProfileSha256: sha256(profileBytes),
    units: "metres", bodyFrame: "+Z forward, +Y up; physical left is +X", eyes };
} finally {
  model.dispose();
}
const rigSha256 = sha256(JSON.stringify(rig));
// Generate actual runtime immutability as well as readonly TypeScript inference.
function immutable(value) {
  if (Array.isArray(value)) return `Object.freeze([${value.map(immutable).join(", ")}] as const)`;
  if (value && typeof value === "object") return `Object.freeze({\n${Object.entries(value).map(([key, item]) => `  ${key}: ${immutable(item)},`).join("\n")}\n})`;
  return JSON.stringify(value);
}
const output = `// Generated by specs/retinal-vision/assets/03/export-eye-rig.mjs; do not edit.\n// Neutral asset centres and reference optical axes; apply the full native body pose.\nexport const retinalEyeRig = ${immutable({ rigSha256, ...rig })};\n`;
const provenance = { rigSha256, threeRevision: REVISION, asset: "assets/fly/fly.glb",
  measurement: "GLTFLoader bind pose -> updateMatrixWorld -> skeleton.update -> precise skinned Box3 centre; native asset metres, no scale/animation",
  sourceProfile: "specs/retinal-vision/assets/01/reference-profile.json", boundsByMesh };
const provenanceText = JSON.stringify(provenance, null, 2) + "\n";
if (process.argv.includes("--check")) {
  assert.equal(await readFile(outputPath, "utf8"), output, "Eye rig is stale; regenerate from authored asset");
  assert.equal(await readFile(new URL("eye-rig-provenance.json", import.meta.url), "utf8"), provenanceText, "Eye rig provenance is stale");
} else {
  await writeFile(outputPath, output);
  await writeFile(new URL("eye-rig-provenance.json", import.meta.url), provenanceText);
}
console.log(JSON.stringify({ rigSha256, eyes: rig.eyes }));
